export function useLang() {
  const { i18n } = useTranslation();
  const lang = (i18n.language || 'en').slice(0, 2) === 'fr' ? 'fr' : 'en';
  const t = useCallback((key) => STRINGS[lang][key] ?? STRINGS.en[key] ?? key, [lang]);
  const setLang = useCallback((l) => i18n.changeLanguage(l), [i18n]);
  return { lang, t, setLang };
}

export const plural = (t, n, one, many) => `${n} ${t(n === 1 ? one : many)}`;
